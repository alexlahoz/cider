#!/usr/bin/env python3
"""Regenerates App/Resources/{en,es}.lproj/Localizable.strings.

Source strings in the Swift code are English. Spanish lives in scripts/l10n/es.py.

Usage:
  scripts/l10n/extract.sh > /tmp/keys.json        # keys used by the code (via swiftc)
  scripts/l10n/generate.py /tmp/keys.json
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from es import ES

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
keys = [k for k in json.load(open(sys.argv[1])) if k] if len(sys.argv) > 1 else sorted(ES)
missing = [k for k in keys if k not in ES]
if missing:
    print('Missing Spanish translations:')
    for m in missing:
        print('  ', repr(m))
    sys.exit(1)


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


for lang, table in (('en', {k: k for k in keys}), ('es', {k: ES[k] for k in keys})):
    path = os.path.join(root, 'App', 'Resources', f'{lang}.lproj', 'Localizable.strings')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('/* Generated by scripts/l10n/generate.py */\n\n')
        for k in sorted(table):
            f.write(f'"{esc(k)}" = "{esc(table[k])}";\n')
    print(path, len(table))
